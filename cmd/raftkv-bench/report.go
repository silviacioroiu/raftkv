// markdown renders the results as the tables embedded in the README.
func markdown(r Results) string {
	var b strings.Builder
	s, e := r.Settings, r.Env

	fmt.Fprintf(&b, "<!-- Generated by cmd/raftkv-bench on %s. Do not edit by hand. -->\n\n", e.Date)
	b.WriteString("### Throughput and latency\n\n")
	b.WriteString("| Nodes | Clients | Throughput (ops/s) | p50 (ms) | p99 (ms) |\n")
	b.WriteString("|------:|--------:|-------------------:|---------:|---------:|\n")
	for _, p := range r.Throughput {
		fmt.Fprintf(&b, "| %d | %d | %s | %s | %s |\n",
			p.Nodes, p.Clients, comma(int(math.Round(p.OpsPerSec))), compact(p.P50Ms), compact(p.P99Ms))
	}

	if len(r.Failover) > 0 {
		b.WriteString("\n### Leader failover\n\n")
		// With this few crashes per size a 95th percentile would just be the
		// maximum under another name, so the table shows the range instead.
		b.WriteString("| Nodes | Crashes | New leader elected: median (ms) | min | max | Client can write again: median (ms) | min | max |\n")
		b.WriteString("|------:|--------:|--------------------------------:|----:|----:|------------------------------------:|----:|----:|\n")
		for _, f := range r.Failover {
			fmt.Fprintf(&b, "| %d | %d | %.0f | %.0f | %.0f | %.0f | %.0f | %.0f |\n",
				f.Nodes, len(f.ElectionMs), f.ElectionP50, smallest(f.ElectionMs), f.ElectionMax,
				f.ClientP50, smallest(f.ClientMs), f.ClientMax)
		}
	}

	b.WriteString("\n### How these were measured\n\n")
	if e.Machine != "" {
		fmt.Fprintf(&b, "- Machine: %s\n", e.Machine)
	}
	fmt.Fprintf(&b, "- %s, %s/%s, %d logical CPUs, measured %s\n", e.GoVersion, e.OS, e.Arch, e.CPUs, e.Date)
	fmt.Fprintf(&b, "- Transport: %s\n", e.Transport)
	fmt.Fprintf(&b, "- Storage: one directory per node on the same disk, fsync %s\n", onOff(s.Fsync))
	fmt.Fprintf(&b, "- Workload: %s; %d keys, %d-byte values\n", s.Workload, s.Keys, s.ValueBytes)
	fmt.Fprintf(&b, "- Each data point: %.0fs warm-up, then %.0fs measured\n", s.WarmupSec, s.DurationSec)
	fmt.Fprintf(&b, "- Raft: election timeout %d-%d ms, heartbeat %d ms, snapshot every %d entries\n",
		s.ElectionTimeoutMs[0], s.ElectionTimeoutMs[1], s.HeartbeatMs, s.SnapshotThreshold)
	return b.String()
}

func smallest(v []float64) float64 {
	if len(v) == 0 {
		return 0
	}
	m := v[0]
	for _, x := range v {
		m = math.Min(m, x)
	}
	return m
}

func onOff(v bool) string {
	if v {
		return "on"
	}
	return "off"
}

// charts renders the results as SVG files, keyed by file name.
func charts(r Results) map[string]string {
	out := make(map[string]string)
	if len(r.Throughput) == 0 {
		return out
	}

	// Throughput: one line per cluster size across client counts.
	var xs []string
	for _, c := range r.Settings.Clients {
		xs = append(xs, strconv.Itoa(c))
	}
	var lines []series
	for _, n := range r.Settings.Sizes {
		s := series{name: fmt.Sprintf("%d nodes", n)}
		for _, c := range r.Settings.Clients {
			s.values = append(s.values, find(r, n, c).OpsPerSec)
		}
		lines = append(lines, s)
	}
	out["throughput.svg"] = lineChart(chart{
		title:    "Throughput by number of concurrent clients",
		subtitle: "Operations per second, 50% Put / 50% Get, fsync " + onOff(r.Settings.Fsync),
		xTitle:   "Concurrent clients",
		unit:     "ops/s",
		labels:   xs,
		series:   lines,
	})

	// Latency: p50 and p99 per cluster size, at a moderate load.
	load := r.Settings.Clients[len(r.Settings.Clients)-1]
	for _, c := range r.Settings.Clients {
		if c == 16 {
			load = c
		}
	}
	var sizes []string
	p50, p99 := series{name: "p50"}, series{name: "p99"}
	for _, n := range r.Settings.Sizes {
		sizes = append(sizes, fmt.Sprintf("%d nodes", n))
		p := find(r, n, load)
		p50.values = append(p50.values, p.P50Ms)
		p99.values = append(p99.values, p.P99Ms)
	}
	out["latency.svg"] = barChart(chart{
		title:    "Request latency by cluster size",
		subtitle: fmt.Sprintf("Milliseconds per request with %d concurrent clients", load),
		xTitle:   "Cluster size",
		unit:     "ms",
		labels:   sizes,
		series:   []series{p50, p99},
	})

	if len(r.Failover) > 0 {
		var labels []string
		elect, client := series{name: "New leader elected"}, series{name: "Client can write again"}
		for _, f := range r.Failover {
			labels = append(labels, fmt.Sprintf("%d nodes", f.Nodes))
			elect.values = append(elect.values, f.ElectionP50)
			client.values = append(client.values, f.ClientP50)
		}
		out["failover.svg"] = barChart(chart{
			title: "Recovery time after the leader crashes",
			subtitle: fmt.Sprintf("Median milliseconds over %d crashes per cluster size, election timeout %d-%d ms",
				r.Settings.FailoverTrials, r.Settings.ElectionTimeoutMs[0], r.Settings.ElectionTimeoutMs[1]),
			xTitle: "Cluster size",
			unit:   "ms",
			labels: labels,
			series: []series{elect, client},
		})
	}
	return out
}

func find(r Results, nodes, clients int) ThroughputPoint {
	for _, p := range r.Throughput {
		if p.Nodes == nodes && p.Clients == clients {
			return p
		}
	}
	return ThroughputPoint{}
}

type series struct {
	name   string
	values []float64
}

type chart struct {
	title, subtitle, xTitle, unit string
	labels                        []string // one per x position
	series                        []series // at most three
}

// Chart geometry, in SVG user units.
const (
	width, height    = 720, 420
	left, right      = 64, 116
	top, bottom      = 104, 56
	plotW            = width - left - right
	plotH            = height - top - bottom
	baseline         = top + plotH
	maxBarWidth      = 24.0
	barGap           = 2.0
	labelClearance   = 14.0
	markerRadius     = 4
	cornerRadius     = 4.0
	legendY          = 78
	legendSwatch     = 10
	legendItemGap    = 22
	approxCharWidth  = 6.6 // 12px system sans, for laying out the legend
	seriesColorCount = 3
)

// The palette: three categorical hues that stay distinguishable under the
// common colour-vision deficiencies, with separate steps for dark mode.
const style = `<style>
  :root { --surface:#fcfcfb; --ink:#0b0b0b; --ink2:#52514e; --muted:#898781; --grid:#e1e0d9; --axis:#c3c2b7;
          --s1:#2a78d6; --s2:#eb6834; --s3:#1baf7a; }
  @media (prefers-color-scheme: dark) {
    :root { --surface:#1a1a19; --ink:#ffffff; --ink2:#c3c2b7; --muted:#898781; --grid:#2c2c2a; --axis:#383835;
            --s1:#3987e5; --s2:#d95926; --s3:#199e70; }
  }
  text { font-family: system-ui, -apple-system, "Segoe UI", sans-serif; }
  .surface { fill: var(--surface); }
  .title { font-size: 16px; font-weight: 600; fill: var(--ink); }
  .subtitle { font-size: 12px; fill: var(--ink2); }
  .legend, .direct { font-size: 12px; fill: var(--ink2); }
  .tick { font-size: 11px; fill: var(--muted); font-variant-numeric: tabular-nums; }
  .axis-title { font-size: 12px; fill: var(--ink2); }
  .value { font-size: 11px; fill: var(--ink2); font-variant-numeric: tabular-nums; }
  .grid { stroke: var(--grid); stroke-width: 1; }
  .base { stroke: var(--axis); stroke-width: 1; }
  .line { fill: none; stroke-width: 2; stroke-linejoin: round; stroke-linecap: round; }
  .dot { stroke: var(--surface); stroke-width: 2; }
  .c1 { stroke: var(--s1); } .c2 { stroke: var(--s2); } .c3 { stroke: var(--s3); }
  .f1 { fill: var(--s1); } .f2 { fill: var(--s2); } .f3 { fill: var(--s3); }
</style>`

// frame draws everything the two chart types share: surface, titles, legend,
// horizontal gridlines with tick labels, x labels and the baseline. It
// returns the y-scale it chose.
func frame(b *strings.Builder, c chart, lineKeys bool, xAt func(i int) float64) func(v float64) float64 {
	if len(c.series) > seriesColorCount {
		panic("chart: more series than validated colours")
	}
	max := 0.0
	for _, s := range c.series {
		for _, v := range s.values {
			max = math.Max(max, v)
		}
	}
	step, ceiling := niceScale(max)
	y := func(v float64) float64 { return baseline - v/ceiling*plotH }

	fmt.Fprintf(b, `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 %d %d" width="%d" height="%d" role="img" aria-labelledby="t d">`+"\n",
		width, height, width, height)
	fmt.Fprintf(b, "<title id=\"t\">%s</title>\n<desc id=\"d\">%s. %s</desc>\n", esc(c.title), esc(c.subtitle), esc(describe(c)))
	b.WriteString(style + "\n")
	fmt.Fprintf(b, `<rect class="surface" width="%d" height="%d" rx="8"/>`+"\n", width, height)
	fmt.Fprintf(b, `<text class="title" x="%d" y="34">%s</text>`+"\n", left-40, esc(c.title))
	fmt.Fprintf(b, `<text class="subtitle" x="%d" y="54">%s</text>`+"\n", left-40, esc(c.subtitle))

	// Legend, in one row under the subtitle.
	x := float64(left - 40)
	for i, s := range c.series {
		if lineKeys {
			fmt.Fprintf(b, `<line class="line c%d" x1="%.1f" y1="%d" x2="%.1f" y2="%d"/>`, i+1, x, legendY-4, x+16, legendY-4)
			fmt.Fprintf(b, `<circle class="dot f%d" cx="%.1f" cy="%d" r="%d"/>`, i+1, x+8, legendY-4, markerRadius)
			x += 16
		} else {
			fmt.Fprintf(b, `<rect class="f%d" x="%.1f" y="%d" width="%d" height="%d" rx="2"/>`, i+1, x, legendY-legendSwatch+1, legendSwatch, legendSwatch)
			x += legendSwatch
		}
		fmt.Fprintf(b, `<text class="legend" x="%.1f" y="%d">%s</text>`+"\n", x+6, legendY, esc(s.name))
		x += 6 + float64(len(s.name))*approxCharWidth + legendItemGap
	}

	for v := 0.0; v <= ceiling+step/2; v += step {
		if v > 0 {
			fmt.Fprintf(b, `<line class="grid" x1="%d" y1="%.1f" x2="%d" y2="%.1f"/>`, left, y(v), left+plotW, y(v))
		}
		fmt.Fprintf(b, `<text class="tick" x="%d" y="%.1f" text-anchor="end">%s</text>`+"\n", left-8, y(v)+4, tickLabel(v, step))
	}
	fmt.Fprintf(b, `<line class="base" x1="%d" y1="%d" x2="%d" y2="%d"/>`+"\n", left, baseline, left+plotW, baseline)
	for i, label := range c.labels {
		fmt.Fprintf(b, `<text class="tick" x="%.1f" y="%d" text-anchor="middle">%s</text>`+"\n", xAt(i), baseline+18, esc(label))
	}
	fmt.Fprintf(b, `<text class="axis-title" x="%.1f" y="%d" text-anchor="middle">%s</text>`+"\n",
		float64(left)+plotW/2.0, height-14, esc(c.xTitle))
	return y
}

func lineChart(c chart) string {
	var b strings.Builder
	inset := 20.0
	xAt := func(i int) float64 {
		if len(c.labels) == 1 {
			return left + plotW/2.0
		}
		return left + inset + (plotW-2*inset)*float64(i)/float64(len(c.labels)-1)
	}
	y := frame(&b, c, true, xAt)

	for i, s := range c.series {
		var path strings.Builder
		for j, v := range s.values {
			cmd := "L"
			if j == 0 {
				cmd = "M"
			}
			fmt.Fprintf(&path, "%s%.1f %.1f ", cmd, xAt(j), y(v))
		}
		fmt.Fprintf(&b, `<path class="line c%d" d="%s"/>`+"\n", i+1, strings.TrimSpace(path.String()))
	}
	// Markers go on top of every line, each with a surface-coloured ring so
	// that it stays readable where lines cross.
	for i, s := range c.series {
		for j, v := range s.values {
			fmt.Fprintf(&b, `<circle class="dot f%d" cx="%.1f" cy="%.1f" r="%d"><title>%s, %s: %s %s</title></circle>`+"\n",
				i+1, xAt(j), y(v), markerRadius, esc(s.name), esc(c.labels[j])+" "+strings.ToLower(esc(c.xTitle)), comma(int(math.Round(v))), c.unit)
		}
	}

	// Name each line at its right end, unless two ends are too close for
	// the names to sit beside their own lines; the legend covers that case.
	last := len(c.labels) - 1
	clear := true
	for i := range c.series {
		for j := range c.series {
			if i < j && math.Abs(y(c.series[i].values[last])-y(c.series[j].values[last])) < labelClearance {
				clear = false
			}
		}
	}
	if clear {
		for _, s := range c.series {
			fmt.Fprintf(&b, `<text class="direct" x="%.1f" y="%.1f">%s</text>`+"\n",
				xAt(last)+12, y(s.values[last])+4, esc(s.name))
		}
	}
	b.WriteString("</svg>\n")
	return b.String()
}

func barChart(c chart) string {
	var b strings.Builder
	band := float64(plotW) / float64(len(c.labels))
	xAt := func(i int) float64 { return left + band*(float64(i)+0.5) }
	y := frame(&b, c, false, xAt)

	k := float64(len(c.series))
	barW := math.Min(maxBarWidth, (band*0.6-barGap*(k-1))/k)
	groupW := k*barW + (k-1)*barGap
	for g := range c.labels {
		x0 := xAt(g) - groupW/2
		for i, s := range c.series {
			v := s.values[g]
			x, yTop := x0+float64(i)*(barW+barGap), y(v)
			r := math.Min(cornerRadius, math.Min(baseline-yTop, barW/2))
			// Rounded at the data end, square on the baseline.
			fmt.Fprintf(&b, `<path class="f%d" d="M%.1f %d L%.1f %.1f Q%.1f %.1f %.1f %.1f L%.1f %.1f Q%.1f %.1f %.1f %.1f L%.1f %d Z"><title>%s, %s: %s %s</title></path>`,
				i+1, x, baseline, x, yTop+r, x, yTop, x+r, yTop, x+barW-r, yTop, x+barW, yTop, x+barW, yTop+r, x+barW, baseline,
				esc(c.labels[g]), esc(s.name), compact(v), c.unit)
			fmt.Fprintf(&b, `<text class="value" x="%.1f" y="%.1f" text-anchor="middle">%s</text>`+"\n",
				x+barW/2, yTop-6, compact(v))
		}
	}
	b.WriteString("</svg>\n")
	return b.String()
}

// describe is the text alternative for screen readers.
func describe(c chart) string {
	var parts []string
	for _, s := range c.series {
		var vals []string
		for j, v := range s.values {
			vals = append(vals, fmt.Sprintf("%s %s %s", c.labels[j], compact(v), c.unit))
		}
		parts = append(parts, s.name+": "+strings.Join(vals, ", "))
	}
	return strings.Join(parts, ". ")
}

// niceScale picks a round tick step giving four or five gridlines, and the
// axis ceiling that goes with it.
func niceScale(max float64) (step, ceiling float64) {
	if max <= 0 {
		return 1, 1
	}
	raw := max / 4
	mag := math.Pow(10, math.Floor(math.Log10(raw)))
	for _, m := range []float64{1, 2, 2.5, 5, 10} {
		if step = m * mag; step >= raw {
			break
		}
	}
	return step, math.Ceil(max/step-1e-9) * step
}

func tickLabel(v, step float64) string {
	switch {
	case step >= 1 && step == math.Trunc(step):
		return comma(int(math.Round(v)))
	case step >= 0.1:
		return strconv.FormatFloat(v, 'f', 1, 64)
	default:
		return strconv.FormatFloat(v, 'f', 2, 64)
	}
}

// compact formats a value with about three significant digits.
func compact(v float64) string {
	switch {
	case v >= 100:
		return comma(int(math.Round(v)))
	case v >= 10:
		return strconv.FormatFloat(v, 'f', 1, 64)
	default:
		return strconv.FormatFloat(v, 'f', 2, 64)
	}
}

func comma(n int) string {
	s := strconv.Itoa(n)
	for i := len(s) - 3; i > 0; i -= 3 {
		s = s[:i] + "," + s[i:]
	}
	return s
}

func esc(s string) string { return html.EscapeString(s) }
